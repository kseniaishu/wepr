"""Run the data-quality gate and the reanalysis-vs-station cross-check.

    .venv/bin/python scripts/validate_data.py [--station-check]

Writes two reports, because the two jobs answer different questions:

* `reports/data_quality.md` — is each city's series complete and physically
  sane? This is the gate: a city enters the app only if it passes.
* `reports/reanalysis_validation.md` — how closely does the reanalysis the app
  serves track real station observations, for the two cities where genuine
  station data is in hand?

`--station-check` additionally resolves where Huesca's GHCN station actually sits,
which needs three extra archive requests, so it is opt-in.
"""

from __future__ import annotations

import argparse
import datetime as dt
import sys

import pandas as pd

from wepr import paths
from wepr.cities import VALIDATION_SLUGS, get
from wepr.data import fetch, load, validate

# Columns to show in the quality table, in reading order, with their headers. The
# raw matrix carries more than a reader needs; the gate is about completeness,
# impossible values and the verdict.
_QUALITY_COLUMNS: list[tuple[str, str]] = [
    ("name", "City"),
    ("region", "Region"),
    ("grid_elevation_m", "Grid elev. (m)"),
    ("start", "From"),
    ("end", "To"),
    ("rows", "Days"),
    ("missing_tavg", "Miss. tavg"),
    ("missing_prcp", "Miss. prcp"),
    ("negative_prcp", "Neg. prcp"),
    ("tmin_above_tmax", "tmin>tmax"),
    ("temp_out_of_range", "Temp. OOR"),
    ("verdict", "Verdict"),
]

_STAT_HEADERS: list[tuple[str, str, str]] = [
    ("n", "Paired days", "{:,.0f}"),
    ("obs_mean", "Station mean", "{:.2f}"),
    ("era_mean", "ERA5 mean", "{:.2f}"),
    ("bias", "Bias (ERA5−station)", "{:+.2f}"),
    ("mae", "MAE", "{:.2f}"),
    ("rmse", "RMSE", "{:.2f}"),
    ("r", "r", "{:.3f}"),
    ("obs_p99", "Station p99", "{:.1f}"),
    ("era_p99", "ERA5 p99", "{:.1f}"),
]


def _table(rows: list[list[str]], headers: list[str]) -> str:
    """A GitHub-flavoured markdown table."""
    out = ["| " + " | ".join(headers) + " |", "|" + "|".join(["---"] * len(headers)) + "|"]
    out += ["| " + " | ".join(row) + " |" for row in rows]
    return "\n".join(out)


def _fmt(value, spec: str = "{}") -> str:
    if value is None or (isinstance(value, float) and pd.isna(value)):
        return "—"
    return spec.format(value)


def quality_report(matrix: pd.DataFrame) -> str:
    """Render `reports/data_quality.md`."""
    keys = [k for k, _ in _QUALITY_COLUMNS if k in matrix.columns]
    headers = [h for k, h in _QUALITY_COLUMNS if k in matrix.columns]

    rows = []
    for slug, row in matrix.iterrows():
        cells = []
        for key in keys:
            value = row.get(key)
            if key.startswith("missing_"):
                cells.append("—" if pd.isna(value) else f"{float(value):.2%}")
            elif key == "grid_elevation_m":
                cells.append(_fmt(value, "{:.0f}"))
            elif key == "rows":
                cells.append(_fmt(value, "{:,.0f}"))
            elif key in ("negative_prcp", "tmin_above_tmax", "temp_out_of_range"):
                # These columns hold NaN for unfetched cities, which makes the whole
                # column float; render them as the integer counts they are.
                cells.append(_fmt(value, "{:.0f}"))
            elif key == "verdict":
                cells.append({"pass": "**pass**", "fail": "**FAIL**"}.get(value, value))
            else:
                cells.append(_fmt(value))
        rows.append(cells)

    passing = (matrix["verdict"] == "pass").sum()
    failing = matrix.index[matrix["verdict"] == "fail"].tolist()
    unfetched = matrix.index[matrix["verdict"] == "not_fetched"].tolist()

    notes = [
        f"- **{passing} of {len(matrix)} cities pass** and may be served by the app.",
    ]
    if failing:
        notes.append("- Failing: " + ", ".join(f"`{s}`" for s in failing))
        for slug in failing:
            notes.append(f"  - `{slug}`: {matrix.loc[slug, 'reasons']}")
    if unfetched:
        notes.append(
            "- Not fetched: " + ", ".join(f"`{s}`" for s in unfetched)
            + " — run `scripts/fetch_data.py`."
        )

    return f"""# Data quality gate

Generated by `scripts/validate_data.py` on {dt.date.today().isoformat()}.
A city is served by the app **only if it passes this gate**. Twenty cities is a
claim about coverage; this table is what makes it a claim about data.

## Provenance

| | |
|---|---|
| Source | Open-Meteo archive API, model `{fetch.MODEL}` |
| Temperature | ERA5-Land, 0.1° (~9 km) |
| Precipitation | ERA5, 0.25° (~28 km) |
| Units as served | °C and mm — **no unit conversion anywhere in this pipeline** |
| Archive lag | ~{fetch.ARCHIVE_LAG_DAYS} days behind real time |

Open-Meteo's `era5_land` model returns `precipitation_sum` as null for **every**
date from 1950 to the present, so requesting it alone would mean no precipitation
at all. `era5_seamless` serves ERA5-Land's temperature verbatim — identical values
on the same 0.1° cell, verified against `era5_land` directly — and fills
precipitation from the coarser ERA5. So this project's temperature is ERA5-Land
and its precipitation is ERA5.

**This is reanalysis, not observation.** ERA5 and ERA5-Land are physical models
with observations assimilated into them. For this project that is defensible and
arguably preferable — complete, gap-free, spatially uniform, 76 years long — but it
is not station measurement, and reanalysis precipitation is materially less
reliable than its temperature, especially for extremes and in mountainous terrain.
The precipitation field is also the lower-resolution of the two here. See
`reports/reanalysis_validation.md` for the cross-check against real station
records.

## Pass criteria

A city passes when **all** of:

- every column at least {1 - validate.MAX_MISSING_FRACTION:.1%} complete (ERA5 has no gaps by
  construction, so the realistic failure this catches is a truncated fetch);
- at least {validate.MIN_YEARS} years of record — below that a day-of-year climatology has too
  few years per calendar day to be stable;
- no physically impossible values: negative precipitation, `tmin > tmax`,
  temperatures outside [{validate.TEMP_MIN_C:.0f}, {validate.TEMP_MAX_C:.0f}] °C, or precipitation above
  {validate.PRCP_MAX_MM:.0f} mm/day.

The sanity envelope is deliberately generous. Its job is to catch corrupt data — a
`-9999` sentinel, a Fahrenheit mix-up, a flipped sign — not to clip genuine weather.
For scale, the Spanish record high is 47.6 °C and the record daily rainfall 817 mm,
both inside the bounds; a 9 km grid cell averages extremes down anyway.

## Per-city matrix

{_table(rows, headers)}

Grid elevation is what the archive served for that coordinate, not the city's
official altitude. It is recorded rather than hard-coded because in broken terrain
the two differ by enough to change how a number should be read.

Note that the `Altitude` region means **broken terrain, not high ground**: it marks
where relief varies steeply inside a ~9 km cell, so one elevation represents the
cell poorly and the reanalysis inherits the error. Granada and Huesca carry it for
sitting under the Sierra Nevada and the Pyrenees respectively — while Salamanca,
Valladolid, Bragança and Madrid are all higher than Huesca yet sit on the flat
meseta, where one elevation per cell is a fair summary, and are `Interior`.

## Verdict

{chr(10).join(notes)}
"""


def validation_report(
    comparisons: dict[str, pd.DataFrame],
    wet: dict[str, float] | None,
    station_check: pd.DataFrame | None,
) -> str:
    """Render `reports/reanalysis_validation.md`."""
    sections: list[str] = []

    overlap = sum(int(t["n"].sum()) for t in comparisons.values())
    if overlap == 0:
        spans = "; ".join(
            f"{get(slug).name} reanalysis {load.load_city(slug).index[0].date()}"
            f"..{load.load_city(slug).index[-1].date()}"
            for slug in comparisons
        )
        return f"""# Reanalysis validated against station observations

Generated by `scripts/validate_data.py` on {dt.date.today().isoformat()}.

**This report could not be produced: there are no overlapping dates.**

The GHCN station records run 1990-2024, and the reanalysis currently on disk covers
{spans}. The cross-check needs dates both sources cover, so it is pending the rest of
the fetch — the archive's free tier caps data volume per day, and a cold 76-year
twenty-city fetch exceeds it.

Re-run `scripts/fetch_data.py` to resume (every year already fetched is cached), then
re-run this script. Fetching works newest-year-first precisely so that the years the
validation needs arrive before the 1950s.
"""

    for slug, table in comparisons.items():
        station = table.attrs["station"]
        rows = []
        for variable, row in table.iterrows():
            cells = [f"`{variable}`"] + [
                _fmt(row.get(key), spec) for key, _, spec in _STAT_HEADERS
            ]
            cells.append(row.get("caveat") or "like-for-like")
            rows.append(cells)
        headers = ["Variable"] + [h for _, h, _ in _STAT_HEADERS] + ["Caveat"]
        sections.append(
            f"### {get(slug).name} — station `{station['station']}`\n\n"
            f"{_table(rows, headers)}\n\n"
            f"Temperatures in °C, precipitation in mm.\n"
        )

    wet_section = ""
    if wet:
        wet_section = f"""## Does it get *whether* it rained right?

A millimetre MAE understates how usable reanalysis precipitation is, because the
error is dominated by a handful of heavy days. Scoring **occurrence** instead, over
a {wet['threshold_mm']:.0f} mm threshold — the convention in the verification literature, and one
that also sidesteps reanalysis "drizzle", the tendency of these models to spread a
little rain over many dry days:

| | |
|---|---|
| Paired days | {wet['n']:,} |
| Station wet days | {wet['obs_wet_days']:,} |
| ERA5 wet days | {wet['era_wet_days']:,} |
| Hits / misses / false alarms | {wet['hits']:,} / {wet['misses']:,} / {wet['false_alarms']:,} |
| Hit rate | {wet['hit_rate']:.3f} |
| False alarm ratio | {wet['false_alarm_ratio']:.3f} |
| Frequency bias | {wet['frequency_bias']:.3f} |
| Mean depth, station vs ERA5 | {wet['obs_mean_mm']:.2f} vs {wet['era_mean_mm']:.2f} mm/day |

This is why the app reports rain **probability** as its headline rather than a
millimetre figure to two decimal places.
"""

    station_section = ""
    if station_check is not None:
        rows = [
            [
                label,
                f"{row['requested_lat']:.4f}, {row['requested_lon']:+.4f}",
                f"{row['grid_lat']:.3f}, {row['grid_lon']:+.3f}",
                f"{row['grid_elevation_m']:.0f}",
                f"{row['tmax_bias']:+.2f}",
                f"{row['tmax_mae']:.2f}",
                f"{row['tmax_r']:.4f}",
            ]
            for label, row in station_check.iterrows()
        ]
        stated = station_check["station_elevation_m"].iloc[0]
        station_section = f"""## Where is the Huesca station, actually?

Huesca's GHCN export states `LONGITUDE 0.3264` — **east** of Greenwich, which would
put the station ~60 km east of the city. That is almost certainly a lost sign: at
42.0831 N, 0.3264 **W** is Huesca-Pirineos airport. Rather than assert that, here
are all three candidate cells scored against the station's own `tmax` record. The
station states its elevation as {stated:.0f} m.

{_table(rows, ["Candidate", "Requested", "Served cell", "Elev. (m)", "tmax bias", "tmax MAE", "tmax r"])}

The westward reading lands on a cell whose elevation matches the station's stated
figure closely, where the eastward reading is hundreds of metres out — so the sign
is lost in the export. The comparison tables above nonetheless use the **city-centre
cell**, because that is the cell the app actually serves: the question worth
answering is how good the served data is, and the gap between the two rows separates
grid mismatch from reanalysis error.
"""

    return f"""# Reanalysis validated against station observations

Generated by `scripts/validate_data.py` on {dt.date.today().isoformat()}.

The app is built on ERA5/ERA5-Land reanalysis. This report checks that choice
against **independent NOAA GHCN-Daily station records** for the two cities where
genuine station data is in hand — the original inputs of this project, now demoted
to a validation set. "I validated the reanalysis against independent station
records" is a materially stronger claim than either source alone.

## Comparing like with like

Two traps that would otherwise be misread as reanalysis error:

- **Definition.** ERA5's `temperature_2m_mean` is a true 24-hour average. Huesca's
  export has no TAVG, so its mean is the midrange `(TMAX + TMIN) / 2`, which runs
  systematically warm — a diurnal curve spends more of the day near its minimum than
  its maximum. So `tmax` and `tmin` are the like-for-like comparisons and `tavg` is
  reported with that caveat attached.
- **Location.** A station is a point; a grid cell is an average over ~9 km (~28 km
  for precipitation). Comparing them is partly a test of spatial representativeness,
  not only of the reanalysis.

Valencia's station record supports a **temperature** comparison only: 43% of its
TMIN, 35% of its TMAX and 17% of its PRCP days are missing, and a precipitation
validation built on that would not be worth reporting. Gaps are left as `NaN`
throughout; forward-filling an observational record invents measurements.

## Agreement

{chr(10).join(sections)}
{wet_section}
{station_section}"""


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--station-check",
        action="store_true",
        help="also resolve the Huesca station location (needs the network)",
    )
    args = parser.parse_args()
    paths.ensure_dirs()

    matrix = validate.quality_matrix()
    (paths.REPORTS / "data_quality.md").write_text(quality_report(matrix))
    matrix.to_csv(paths.REPORTS / "data_quality.csv")

    counts = matrix["verdict"].value_counts().to_dict()
    print(f"quality gate: {counts}")
    for slug in matrix.index[matrix["verdict"] == "fail"]:
        print(f"  FAIL {slug}: {matrix.loc[slug, 'reasons']}", file=sys.stderr)

    available = set(load.available_cities())
    comparisons = {
        slug: validate.compare_with_ghcn(slug)
        for slug in VALIDATION_SLUGS
        if slug in available
    }
    if not comparisons:
        print("no validation city fetched yet; skipping the cross-check", file=sys.stderr)
        return 0 if not (matrix["verdict"] == "fail").any() else 1

    wet = validate.wet_day_agreement("huesca") if "huesca" in comparisons else None
    station_check = (
        validate.station_location_check("huesca")
        if args.station_check and "huesca" in comparisons
        else None
    )

    (paths.REPORTS / "reanalysis_validation.md").write_text(
        validation_report(comparisons, wet, station_check)
    )
    for slug, table in comparisons.items():
        print(f"\n{slug}:")
        print(table.drop(columns="caveat").round(3).to_string())

    print(f"\nreports -> {paths.REPORTS}")
    return 1 if (matrix["verdict"] == "fail").any() else 0


if __name__ == "__main__":
    raise SystemExit(main())
